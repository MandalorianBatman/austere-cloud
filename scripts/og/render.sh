#!/usr/bin/env bash
# Renders scripts/og/og.html to 1200x630 and writes src/og-png.ts (the PNG as base64; the Worker serves it at /og.png).
# Needs Google Chrome and Barlow Condensed Bold (OFL): pass the .ttf path as $1. The font is used for the raster only; it is not shipped.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
font="${1:?usage: render.sh path/to/BarlowCondensed-Bold.ttf}"
tmp="$(mktemp -d)"
cp "$here/og.html" "$tmp/og.html"
cp "$font" "$tmp/BarlowCondensed-Bold.ttf"
"${CHROME:-google-chrome}" --headless=new --no-sandbox --hide-scrollbars --force-device-scale-factor=1 \
  --window-size=1200,630 --screenshot="$tmp/og.png" "file://$tmp/og.html" >/dev/null 2>&1
printf '// Generated by scripts/og/render.sh from scripts/og/og.html. Do not edit.\nexport const OG_PNG_BASE64 =\n  "%s";\n' \
  "$(base64 -w0 "$tmp/og.png")" > "$here/../../src/og-png.ts"
cp "$tmp/og.png" "${OG_OUT:-/dev/null}" 2>/dev/null || true
rm -rf "$tmp"
